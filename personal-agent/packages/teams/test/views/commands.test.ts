/** The command cards beyond their snapshots: the English cards, and what a card leaves out when it has nothing for it. */
import assert from "node:assert/strict";
import { test } from "node:test";

import { bindingCard, linkCard, onboardingCard, repoCard, sessionCard } from "../../src/views/commands/index.js";

function content(card: object): string {
  return JSON.stringify(card);
}

test("the onboarding card mentions only a person it can address, and says when the steps are already sent", () => {
  const sent = content(
    onboardingCard({
      bot: "Clawy",
      name: "A<b>&c",
      channelUserId: "29:x",
      promptId: "p",
      dmSent: true,
      note: "Only A.",
      waitMinutes: 15,
    }),
  );
  assert.ok(sent.includes("<at>A b c</at>, connect Clawy") && sent.includes("I sent you the steps in a 1:1 chat. "));
  assert.ok(sent.includes('"msteams"') && sent.includes("Only A."));
  const anonymous = content(
    onboardingCard({
      bot: "Clawy",
      name: "",
      channelUserId: "",
      promptId: "p",
      dmSent: false,
      note: "",
      waitMinutes: 15,
    }),
  );
  assert.ok(anonymous.includes("You, connect Clawy once") && !anonymous.includes("msteams"));
});

test("the binding card says its lead; the repo and session cards in English", () => {
  assert.ok(
    content(bindingCard({ bot: "Clawy", confirmUrl: "https://x", lead: " Hello. ", notice: "n", lang: "en" })).includes(
      '"Hello."',
    ),
  );
  assert.ok(content(repoCard({ repo: "o/r", branch: "", lang: "en" })).includes("Default branch"));
  assert.ok(content(repoCard({ repo: "o/r", branch: "dev", lang: "en" })).includes("Branch: dev"));
  assert.ok(content(repoCard({ repo: "o/r", branch: "", lang: "zh" })).includes("默认分支"));
  const session = content(
    sessionCard({
      sessionId: "abcdef0123",
      title: "",
      repo: "o/r",
      branch: "",
      when: "yesterday 18:05",
      current: false,
      lang: "en",
      publicBaseUrl: "http://plain.example",
    }),
  );
  assert.ok(session.includes("Session abcdef01") && session.includes("Last used yesterday 18:05"));
  assert.ok(session.includes('"value":"o/r"') && !session.includes("Open in Claw")); // (no https: no link)
  const current = content(
    sessionCard({
      sessionId: "s",
      title: "t",
      repo: "",
      branch: "",
      when: "today 12:40",
      current: true,
      lang: "en",
      publicBaseUrl: "https://claw.example.com/",
    }),
  );
  assert.ok(current.includes("This chat's session now · Last used today 12:40") && current.includes("Open in Claw"));
  const urls = [...current.matchAll(/"url":"([^"]*)"/gu)].map((m) => m[1]);
  assert.deepEqual(urls, ["https://claw.example.com/primus-claw/s"]);
});

test("test_both_connect_cards_render_the_notice", () => {
  const notice = "Answers are generated by AI and may be incomplete or wrong.";
  const link = content(linkCard({ bot: "Clawy", who: "a@example.com", page: "https://x/p", notice }));
  const binding = content(bindingCard({ bot: "Clawy", confirmUrl: "https://id.test/c", lead: "", notice, lang: "en" }));
  assert.ok(link.includes(notice) && binding.includes(notice));
});

/** Every text a card shows (its body's text blocks and its buttons' titles), in order. */
function shownTexts(card: object): string[] {
  const out: string[] = [];
  const walk = (node: unknown): void => {
    if (Array.isArray(node)) {
      node.forEach(walk);
      return;
    }
    if (node === null || typeof node !== "object") return;
    const record = node as Record<string, unknown>;
    if (record["type"] === "TextBlock" && typeof record["text"] === "string") out.push(record["text"]);
    if (
      typeof record["type"] === "string" &&
      record["type"].startsWith("Action.") &&
      typeof record["title"] === "string"
    )
      out.push(`[${record["title"]}]`);
    for (const value of Object.values(record)) walk(value);
  };
  walk(card);
  return out;
}

test("the binding card's title, body and buttons follow the person's language: Chinese", () => {
  const card = bindingCard({
    bot: "Clawy",
    confirmUrl: "https://id.test/c",
    lead: "这一步需要你本人：在这张卡片上确认一次身份，然后再说一遍就行。",
    notice: "回答由 AI 生成，可能不完整或有错。重要的事请自己核实后再用。",
    lang: "zh",
  });
  const texts = shownTexts(card);
  for (const expected of [
    "连接 Clawy",
    "这一步需要你本人：在这张卡片上确认一次身份，然后再说一遍就行。",
    "打开链接，登录你的 Primus 账号并确认一次。之后我在 Primus 平台上以你的身份、用你自己的权限做事。",
    "链接只能用一次，10 分钟后失效。我用的是 5 分钟有效的令牌，从不用你的密码。你可以在 SaFE 的身份绑定里删除这个连接。",
    "回答由 AI 生成，可能不完整或有错。重要的事请自己核实后再用。",
    "[打开链接]",
    "[我已确认]",
  ]) {
    assert.ok(
      texts.some((t) => t.includes(expected)),
      `${expected} in ${JSON.stringify(texts)}`,
    );
  }
  assert.ok(!texts.some((t) => /Open the link|Open link|I confirmed|Connect Clawy/u.test(t)), JSON.stringify(texts));
  // (the button still says what it did: the same press as in English)
  assert.ok(content(card).includes('"action":"confirm"') && content(card).includes('"url":"https://id.test/c"'));
});

test("the binding card's title, body and buttons follow the person's language: English", () => {
  const texts = shownTexts(
    bindingCard({
      bot: "Clawy",
      confirmUrl: "https://id.test/c",
      lead: "That needs you in person: confirm your identity once on this card, then ask again.",
      notice: "Answers are generated by AI and may be incomplete or wrong.",
      lang: "en",
    }),
  );
  for (const expected of [
    "Connect Clawy",
    "That needs you in person: confirm your identity once on this card, then ask again.",
    "Open the link, sign in to your Primus account and confirm once.",
    "The link works once and runs out in 10 minutes.",
    "[Open link]",
    "[I confirmed]",
  ]) {
    assert.ok(
      texts.some((t) => t.includes(expected)),
      `${expected} in ${JSON.stringify(texts)}`,
    );
  }
  assert.ok(!texts.some((t) => /[一-鿿]/u.test(t)), JSON.stringify(texts));
});
