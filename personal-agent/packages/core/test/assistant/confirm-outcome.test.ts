it("what came of an instruction card is said in the persons language", () => {
  const done = { status: "done", answered_now: true, result: { seq: 3, machine: "devbox", agent: "codex" } };
  assert.equal(
    confirmOutcome("devenv_send", done, "zh"),
    "已发给 devbox 上的 codex（#3）。做完或需要你批准时我会告诉你。",
  );
  assert.equal(confirmOutcome("devenv_send", { status: "denied" }, "zh"), "好的，没有发送。");
  assert.ok(
    confirmOutcome("devenv_send", { status: "failed", result: { error: "busy" } }, "en").startsWith(
      "That session is working",
    ),
  );
  assert.equal(
    confirmOutcome("devenv_send", { status: "failed", result: { error: "odd" } }, "en"),
    "It could not be sent (odd).",
  );
  // A card made before its machine registered again, for a session that went with the old registration: say what happened.
  assert.equal(
    confirmOutcome("devenv_send", { status: "failed", result: { error: "machine_reconnected" } }, "zh"),
    "这台机器在这张卡之后重新连接过，卡上的会话已经不在了，什么都没发。请再跟我说一次。",
  );
  assert.equal(
    confirmOutcome("trigger_create", { status: "denied" }, "en"),
    "OK, not created.",
    "the scheduled task's words are unchanged",
  );
  const held = {
    type: "assistant.say",
    text: "x",
    confirm_write: { confirmation_id: "cf-1", ref: "cf0001", kind: "devenv_send", allow_label: "发送" },
  };
  assert.deepEqual(confirmWriteOf(held), { confirmationId: "cf-1", kind: "devenv_send", allowLabel: "发送" });
});

